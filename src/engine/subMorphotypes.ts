export function getSubMorphotypesForArchetype(archetype: ArchetypeId): SubMorphotype[] {
  return SUB_MORPHOTYPES[archetype] ?? SUB_MORPHOTYPES.alien;
}

export function findSubMorphotype(archetype: ArchetypeId, id: string): SubMorphotype | undefined {
  return getSubMorphotypesForArchetype(archetype).find((m) => m.id === id);
}

/**
 * Selects a SubMorphotype deterministically from seed using archetype weights,
 * or returns the explicitly chosen sub-morphotype if manualId !== 'auto'.
 */
export function selectSubMorphotype(
  seed: number,
  archetype: ArchetypeId,
  manualId: 'auto' | string = 'auto'
): SubMorphotype {
  const subtypes = getSubMorphotypesForArchetype(archetype);
  if (manualId !== 'auto') {
    const found = subtypes.find((s) => s.id === manualId);
    if (found) return found;
  }

  const rng = new SeededPRNG(seed ^ 0x517cc1b7);
  const totalWeight = subtypes.reduce((acc, s) => acc + Math.max(0.01, s.weight), 0);
  let r = rng.next() * totalWeight;
  for (const sub of subtypes) {
    r -= Math.max(0.01, sub.weight);
    if (r <= 0) return sub;
  }
  return subtypes[0];
}

/**
 * Smoothly interpolates morphological parameters between two sub-morphotypes (hybridization)
 * without abrupt discrete jumps or anatomically incoherent part mixtures.
 */
export function lerpSubMorphotypes(
  primary: SubMorphotype,
  secondary: SubMorphotype,
  blend: number
): SubMorphotype {
  const t = Math.max(0, Math.min(1, blend));
  if (t <= 0.01 || primary.id === secondary.id) return primary;

  const lerp = (a: number, b: number) => a + (b - a) * t;
  const pick = <T,>(a: T, b: T, threshold = 0.58): T => (t >= threshold ? b : a);

  const mergedFeatures = Array.from(
    new Set([
      ...primary.specialFeatures,
      ...(t > 0.38 ? secondary.specialFeatures.slice(0, 1) : []),
    ])
  );

  // Smoothly interpolate fore/hind limb counts while ensuring bilateral parity when bilateral
  const rawForeCount = Math.round(lerp(primary.limbConfiguration.forelimbs.count, secondary.limbConfiguration.forelimbs.count));
  const rawHindCount = Math.round(lerp(primary.limbConfiguration.hindlimbs.count, secondary.limbConfiguration.hindlimbs.count));
  const sym = pick(primary.symmetry, secondary.symmetry, 0.68);
  const evenClamp = (n: number) => (sym === 'bilateral' && n % 2 === 1 ? n + 1 : n);

  return {
    ...primary,
    symmetry: sym,
    bodyAxis: pick(primary.bodyAxis, secondary.bodyAxis, 0.62),
    torsoAspect: [
      lerp(primary.torsoAspect[0], secondary.torsoAspect[0]),
      lerp(primary.torsoAspect[1], secondary.torsoAspect[1]),
      lerp(primary.torsoAspect[2], secondary.torsoAspect[2]),
    ],
    limbConfiguration: {
      forelimbs: {
        count: evenClamp(rawForeCount),
        type: pick(primary.limbConfiguration.forelimbs.type, secondary.limbConfiguration.forelimbs.type, 0.55),
        articulation: pick(
          primary.limbConfiguration.forelimbs.articulation,
          secondary.limbConfiguration.forelimbs.articulation,
          0.55
        ),
        lengthScale: lerp(
          primary.limbConfiguration.forelimbs.lengthScale,
          secondary.limbConfiguration.forelimbs.lengthScale
        ),
      },
      hindlimbs: {
        count: evenClamp(rawHindCount),
        type: pick(primary.limbConfiguration.hindlimbs.type, secondary.limbConfiguration.hindlimbs.type, 0.55),
        articulation: pick(
          primary.limbConfiguration.hindlimbs.articulation,
          secondary.limbConfiguration.hindlimbs.articulation,
          0.55
        ),
        lengthScale: lerp(
          primary.limbConfiguration.hindlimbs.lengthScale,
          secondary.limbConfiguration.hindlimbs.lengthScale
        ),
      },
      extraPairs: Math.round(
        lerp(primary.limbConfiguration.extraPairs ?? 0, secondary.limbConfiguration.extraPairs ?? 0)
      ),
    },
    spineSegments: Math.max(1, Math.round(lerp(primary.spineSegments, secondary.spineSegments))),
    spineCurvature: lerp(primary.spineCurvature, secondary.spineCurvature),
    neckRatio: lerp(primary.neckRatio, secondary.neckRatio),
    headScaleRatio: lerp(primary.headScaleRatio, secondary.headScaleRatio),
    headPosition: pick(primary.headPosition, secondary.headPosition, 0.62),
    tailPresence: pick(primary.tailPresence, secondary.tailPresence, 0.55),
    tailType: pick(primary.tailType, secondary.tailType, 0.55),
    tailLengthScale: lerp(primary.tailLengthScale, secondary.tailLengthScale),
    wingPresence: pick(primary.wingPresence, secondary.wingPresence, 0.52),
    wingSpanScale: lerp(primary.wingSpanScale, secondary.wingSpanScale),
    hasFins: primary.hasFins || (t > 0.45 && secondary.hasFins),
    hasTentacles: primary.hasTentacles || (t > 0.55 && secondary.hasTentacles),
    tentacleCount: Math.round(lerp(primary.tentacleCount, secondary.tentacleCount)),
    hasAntennae: primary.hasAntennae || (t > 0.5 && secondary.hasAntennae),
    hasMandibles: primary.hasMandibles || (t > 0.5 && secondary.hasMandibles),
    hasBeak: pick(primary.hasBeak, secondary.hasBeak, 0.6),
    hasBifidTongue: pick(primary.hasBifidTongue, secondary.hasBifidTongue, 0.6),
    hasDorsalCrest: primary.hasDorsalCrest || (t > 0.5 && secondary.hasDorsalCrest),
    shellType: pick(primary.shellType, secondary.shellType, 0.58),
    eyeCount: Math.round(lerp(primary.eyeCount, secondary.eyeCount)),
    eyeScaleBias: lerp(primary.eyeScaleBias, secondary.eyeScaleBias),
    specialFeatures: mergedFeatures,
  };
}

/**
 * Evaluates structural diversity across N generated seeds within an archetype
 * (verifies sub-morphotype spread, limb variance, body/limb ratio spread, and specializations).
 */
export function evaluateArchetypeDiversity(
  archetype: ArchetypeId,
  baseSeed: number,
  sampleCount = 50
): ArchetypeDiversityReport {
  const available = getSubMorphotypesForArchetype(archetype);
  const uniqueSubs = new Set<string>();
  const uniqueSym = new Set<SymmetryMode>();

  let minLimbs = Infinity;
  let maxLimbs = -Infinity;
  let minRatio = Infinity;
  let maxRatio = -Infinity;
  let specializedCount = 0;

  for (let i = 0; i < sampleCount; i++) {
    const s = (baseSeed + i * 7919) % 9999999;
    const sub = selectSubMorphotype(s, archetype, 'auto');
    uniqueSubs.add(sub.id);
    uniqueSym.add(sub.symmetry);

    const totalLimbs =
      sub.limbConfiguration.forelimbs.count +
      sub.limbConfiguration.hindlimbs.count +
      sub.tentacleCount;
    minLimbs = Math.min(minLimbs, totalLimbs);
    maxLimbs = Math.max(maxLimbs, totalLimbs);

    const avgLimbScale =
      totalLimbs > 0
        ? (sub.limbConfiguration.forelimbs.lengthScale * sub.limbConfiguration.forelimbs.count +
            sub.limbConfiguration.hindlimbs.lengthScale * sub.limbConfiguration.hindlimbs.count +
            sub.tentacleCount * 1.0) /
          totalLimbs
        : 0.3;
    const ratio = sub.torsoAspect[2] / Math.max(0.3, avgLimbScale);
    minRatio = Math.min(minRatio, ratio);
    maxRatio = Math.max(maxRatio, ratio);

    if (
      sub.wingPresence !== 'none' ||
      sub.shellType !== 'none' ||
      sub.specialFeatures.length >= 2 ||
      sub.limbConfiguration.forelimbs.type === 'flipper' ||
      sub.limbConfiguration.forelimbs.type === 'raptorial' ||
      sub.limbConfiguration.forelimbs.type === 'chela'
    ) {
      specializedCount++;
    }
  }

  return {
    sampleCount,
    uniqueSubMorphotypes: uniqueSubs.size,
    totalAvailableSubMorphotypes: available.length,
    minLimbs: Number.isFinite(minLimbs) ? minLimbs : 0,
    maxLimbs: Number.isFinite(maxLimbs) ? maxLimbs : 0,
    minBodyLimbRatio: Number.isFinite(minRatio) ? Number(minRatio.toFixed(2)) : 1,
    maxBodyLimbRatio: Number.isFinite(maxRatio) ? Number(maxRatio.toFixed(2)) : 1,
    uniqueSymmetries: Array.from(uniqueSym),
    specializedCount,
    passesValidation: uniqueSubs.size >= Math.min(6, available.length) && specializedCount >= 2,
  };
}
